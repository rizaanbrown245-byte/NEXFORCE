/**
 * Returns today's daily motivation quote based on the current calendar day
 */
export function getDailyMotivationQuote(): MotivationQuote {
  const now = new Date();
  const startOfYear = new Date(now.getFullYear(), 0, 0);
  const diff = now.getTime() - startOfYear.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);

  const index = (now.getFullYear() * 31 + dayOfYear) % MOTIVATION_QUOTES.length;
  return MOTIVATION_QUOTES[index];
}

/**
 * Returns a random motivation quote
 */
export function getRandomMotivationQuote(excludeId?: string): MotivationQuote {
  const filtered = excludeId
    ? MOTIVATION_QUOTES.filter((q) => q.id !== excludeId)
    : MOTIVATION_QUOTES;
  const randomIndex = Math.floor(Math.random() * filtered.length);
  return filtered[randomIndex] || MOTIVATION_QUOTES[0];
}
